/// نصوص الأذكار والأدعية. راجِعها على مصدر موثوق قبل النشر.
class Dhikr {
  final String text;
  final int count;
  const Dhikr(this.text, this.count);
}

class DhikrGroup {
  final String id; // مفتاح ترجمة: g_<id>
  final List<Dhikr> items;
  const DhikrGroup(this.id, this.items);
}

